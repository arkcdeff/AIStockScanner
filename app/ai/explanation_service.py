class AINotFoundError(Exception):
    pass


def build_fallback_stock_payload(
    stock: AIStockContext, analytics: AIAnalyticsContext
) -> AIExplanationPayload:
    overall = analytics.overall_score
    if overall >= 70:
        tone = "constructive"
    elif overall >= 45:
        tone = "neutral"
    else:
        tone = "cautious"
    return AIExplanationPayload(
        summary=(
            f"{stock.symbol} scores {overall}/100 overall as of {stock.trade_date}, "
            f"a {tone} reading based on the supplied analytics."
        ),
        medium_summary=(
            f"Trend scores {analytics.trend_score}/100 and momentum scores "
            f"{analytics.momentum_score}/100 on {stock.trade_date}."
        ),
        detailed_summary=(
            f"{stock.symbol} ({stock.company_name}) has an overall score of {overall}/100. "
            f"Trend is {analytics.trend_rating or 'unrated'}, momentum is "
            f"{analytics.momentum_rating or 'unrated'}, and volatility is "
            f"{analytics.volatility_rating or 'unrated'}. "
            f"It is {'trending' if analytics.is_trending else 'not flagged as trending'} and "
            f"{'showing a breakout' if analytics.is_breakout else 'not showing a breakout'}."
        ),
        strengths=[
            f"Overall score of {overall}/100",
            f"Trend rating: {analytics.trend_rating or 'N/A'}",
            f"Momentum rating: {analytics.momentum_rating or 'N/A'}",
        ],
        risks=[
            f"Volatility rating: {analytics.volatility_rating or 'N/A'}",
            "Explanation generated by deterministic fallback (provider unavailable).",
        ],
        support=[f"{analytics.support:.2f}" if analytics.support is not None else "N/A"],
        resistance=[f"{analytics.resistance:.2f}" if analytics.resistance is not None else "N/A"],
        scanner_explanation=(
            "Scanner details are unavailable in fallback mode; see the scanner matches panel."
        ),
        trend_explanation=f"Trend score is {analytics.trend_score}/100.",
        risk_explanation=f"Volatility rating is {analytics.volatility_rating or 'unrated'}.",
        confidence=min(100, max(0, overall)),
    )


class AIExplanationService:
    def __init__(
        self,
        session: AsyncSession,
        provider: BaseAIProvider | None = None,
    ) -> None:
        self.session = session
        self.provider = provider or get_provider()
        self.memory_cache = get_memory_cache()
        self.stock_repo = StockDetailRepository(session)
        self.ai_repo = AIExplanationRepository(session)

    # ------------------------------------------------------------------ public

    async def explain_stock(self, symbol: str) -> AIStockExplanationResponse:
        stock = await self.stock_repo.get_stock(symbol)
        if stock is None:
            raise AINotFoundError(f"Stock not found: {symbol}")
        analytics = await self.stock_repo.get_latest_analytics(stock.id)
        if analytics is None:
            raise AINotFoundError(f"No analytics found for {symbol}")

        latest_price = await self.stock_repo.get_latest_price(stock.id)
        indicator = await self.stock_repo.get_latest_indicator(stock.id)
        matches = await self.stock_repo.get_scanner_matches(stock.id)
        pipeline = await self._get_pipeline_status()

        stock_ctx = self._build_stock_context(stock, analytics, latest_price)
        analytics_ctx = self._build_analytics_context(analytics)
        indicator_ctx = self._build_indicator_context(indicator)
        match_ctx = [self._build_match_context(m) for m in matches]

        prompt = build_stock_summary_prompt(
            stock_ctx, analytics_ctx, indicator_ctx, match_ctx, pipeline
        )
        prompt_hash = hash_prompt(prompt)
        cache_key = f"ai:{self.provider.name}:{prompt_hash}"

        cached = self.memory_cache.get(cache_key)
        if cached is not None:
            return cast(AIStockExplanationResponse, cached).model_copy(
                update={"source": "cache"}
            )

        existing = await self.ai_repo.get_by_stock_date_provider(
            stock.id, analytics.trade_date, self.provider.name
        )
        if existing is not None and existing.prompt_hash == prompt_hash:
            try:
                payload = parse_stock_explanation(existing.response)
            except AIResponseError:
                payload = None
            if payload is not None:
                response = self._build_stock_response(stock, analytics, payload, "cache")
                self.memory_cache.set(cache_key, response)
                return response

        try:
            raw = await self.provider.generate(prompt, timeout_seconds=settings.ai_timeout)
            payload = parse_stock_explanation(raw)
            source = "generated"
        except (AIProviderError, AIResponseError) as exc:
            logger.warning("AI explanation failed for {}: {}", symbol, exc)
            payload = build_fallback_stock_payload(stock_ctx, analytics_ctx)
            source = "fallback"

        stored_response = json.dumps(payload.model_dump(), ensure_ascii=False)
        await self.ai_repo.upsert(
            stock.id,
            analytics.trade_date,
            self.provider.name,
            self.provider.model_name(),
            prompt_hash,
            stored_response,
            payload.confidence,
        )
        await self.session.commit()

        response = self._build_stock_response(stock, analytics, payload, source)
        self.memory_cache.set(cache_key, response)
        return response

    async def explain_top_rated(self, limit: int = 5) -> AICollectionExplanationResponse:
        rows = await self._top_rated_rows(limit=limit)
        pipeline = await self._get_pipeline_status()
        stock_ctxs = await self._build_stock_contexts(rows)
        items = self._build_analytics_items(rows)

        prompt = build_scanner_summary_prompt(stock_ctxs, pipeline)
        prompt_hash = hash_prompt(prompt)
        cache_key = f"ai:{self.provider.name}:{prompt_hash}"

        cached = self.memory_cache.get(cache_key)
        if cached is not None:
            return cast(AICollectionExplanationResponse, cached).model_copy(
                update={"source": "cache"}
            )

        try:
            raw = await self.provider.generate(prompt, timeout_seconds=settings.ai_timeout)
            payload = parse_collection_explanation(raw)
            source = "generated"
        except (AIProviderError, AIResponseError) as exc:
            logger.warning("AI scanner explanation failed: {}", exc)
            payload = self._build_fallback_collection_payload(items)
            source = "fallback"

        response = AICollectionExplanationResponse(
            trade_date=self._latest_trade_date(rows),
            provider=self.provider.name,
            model=self.provider.model_name(),
            source=source,  # type: ignore[arg-type]
            stocks=items,
            **payload.model_dump(),
        )
        self.memory_cache.set(cache_key, response)
        return response

    async def explain_market_summary(self, limit: int = 8) -> AIMarketSummaryResponse:
        rows = await self._top_rated_rows(limit=limit)
        pipeline = await self._get_pipeline_status()
        stock_ctxs = await self._build_stock_contexts(rows)
        items = self._build_analytics_items(rows)
        stock_count = len(rows)

        prompt = build_market_summary_prompt(stock_ctxs, pipeline, stock_count)
        prompt_hash = hash_prompt(prompt)
        cache_key = f"ai:{self.provider.name}:{prompt_hash}"

        cached = self.memory_cache.get(cache_key)
        if cached is not None:
            return cast(AIMarketSummaryResponse, cached).model_copy(
                update={"source": "cache"}
            )

        try:
            raw = await self.provider.generate(prompt, timeout_seconds=settings.ai_timeout)
            payload = parse_market_explanation(raw)
            source = "generated"
        except (AIProviderError, AIResponseError) as exc:
            logger.warning("AI market explanation failed: {}", exc)
            payload = self._build_fallback_market_payload(items)
            source = "fallback"

        response = AIMarketSummaryResponse(
            trade_date=self._latest_trade_date(rows),
            provider=self.provider.name,
            model=self.provider.model_name(),
            source=source,  # type: ignore[arg-type]
            stock_count=stock_count,
            top_rated=items,
            **payload.model_dump(),
        )
        self.memory_cache.set(cache_key, response)
        return response

    # ------------------------------------------------------------------ context

    def _build_stock_context(
        self,
        stock: Stock,
        analytics: TechnicalAnalysis,
        latest_price: DailyPrice | None,
    ) -> AIStockContext:
        price_change_pct = None
        if latest_price and latest_price.previous_close:
            prev = float(latest_price.previous_close)
            if prev:
                price_change_pct = round(
                    (float(latest_price.close) - prev) / prev * 100, 2
                )
        return AIStockContext(
            symbol=stock.symbol,
            company_name=stock.company_name,
            sector=stock.sector_ref.name if stock.sector_ref else None,
            industry=stock.industry,
            exchange=stock.exchange,
            trade_date=analytics.trade_date,
            latest_close=float(latest_price.close) if latest_price else None,
            price_change_pct=price_change_pct,
            volume=int(latest_price.volume) if latest_price and latest_price.volume else None,
            delivery_percentage=float(latest_price.delivery_percentage)
            if latest_price and latest_price.delivery_percentage is not None
            else None,
        )

    def _build_analytics_context(self, analytics: TechnicalAnalysis) -> AIAnalyticsContext:
        return AIAnalyticsContext(
            overall_score=analytics.overall_score,
            trend_score=analytics.trend_score,
            momentum_score=analytics.momentum_score,
            volume_score=analytics.volume_score,
            delivery_score=analytics.delivery_score,
            volatility_score=analytics.volatility_score,
            support=float(analytics.support) if analytics.support is not None else None,
            resistance=float(analytics.resistance) if analytics.resistance is not None else None,
            pivot=float(analytics.pivot) if analytics.pivot is not None else None,
            trend_rating=analytics.trend_rating,
            momentum_rating=analytics.momentum_rating,
            volatility_rating=analytics.volatility_rating,
            is_trending=analytics.is_trending,
            is_breakout=analytics.is_breakout,
        )

    def _build_indicator_context(
        self, indicator: IndicatorResult | None
    ) -> AIIndicatorContext | None:
        if indicator is None:
            return None
        return AIIndicatorContext(
            trade_date=indicator.trade_date,
            ema_20=float(indicator.ema_20) if indicator.ema_20 is not None else None,
            ema_50=float(indicator.ema_50) if indicator.ema_50 is not None else None,
            ema_100=float(indicator.ema_100) if indicator.ema_100 is not None else None,
            ema_200=float(indicator.ema_200) if indicator.ema_200 is not None else None,
            sma=float(indicator.sma) if indicator.sma is not None else None,
            rsi_14=float(indicator.rsi_14) if indicator.rsi_14 is not None else None,
            macd=float(indicator.macd) if indicator.macd is not None else None,
            macd_signal=float(indicator.macd_signal) if indicator.macd_signal is not None else None,
            macd_hist=float(indicator.macd_hist) if indicator.macd_hist is not None else None,
            atr=float(indicator.atr) if indicator.atr is not None else None,
            adx=float(indicator.adx) if indicator.adx is not None else None,
            supertrend=float(indicator.supertrend) if indicator.supertrend is not None else None,
            supertrend_direction=(
                "bullish" if indicator.supertrend_direction == 1 else "bearish"
            )
            if indicator.supertrend_direction is not None
            else None,
            vwap=float(indicator.vwap) if indicator.vwap is not None else None,
            obv=float(indicator.obv) if indicator.obv is not None else None,
            bollinger_upper=float(indicator.bollinger_upper)
            if indicator.bollinger_upper is not None
            else None,
            bollinger_middle=float(indicator.bollinger_middle)
            if indicator.bollinger_middle is not None
            else None,
            bollinger_lower=float(indicator.bollinger_lower)
            if indicator.bollinger_lower is not None
            else None,
            stochastic_k=float(indicator.stochastic_k)
            if indicator.stochastic_k is not None
            else None,
            stochastic_d=float(indicator.stochastic_d)
            if indicator.stochastic_d is not None
            else None,
        )

    def _build_match_context(self, match: ScanResult) -> AIScannerMatchContext:
        reason = ""
        if match.metrics and isinstance(match.metrics, dict):
            reason = match.metrics.get("reason", "")
        return AIScannerMatchContext(
            scanner_name=match.scan_definition.name if match.scan_definition else "Unknown",
            category=match.scan_definition.category if match.scan_definition else None,
            score=float(match.score) if match.score is not None else None,
            reason=str(reason) if reason else None,
        )

    # ------------------------------------------------------------------ rows

    async def _top_rated_rows(self, limit: int) -> list[TechnicalAnalysis]:
        rows = (
            await self.session.scalars(
                select(TechnicalAnalysis)
                .options(
                    selectinload(TechnicalAnalysis.stock).selectinload(Stock.sector_ref)
                )
                .order_by(TechnicalAnalysis.overall_score.desc())
                .limit(limit)
            )
        ).all()
        return list(rows)

    async def _build_stock_contexts(
        self, rows: list[TechnicalAnalysis]
    ) -> list[AIStockContext]:
        if not rows:
            return []
        stock_ids = [row.stock_id for row in rows]
        price_rows = (
            await self.session.execute(
                select(DailyPrice.stock_id, DailyPrice.close, DailyPrice.trade_date).where(
                    DailyPrice.stock_id.in_(stock_ids),
                    DailyPrice.trade_date.in_(
                        select(TechnicalAnalysis.trade_date).where(
                            TechnicalAnalysis.stock_id.in_(stock_ids)
                        )
                    ),
                )
            )
        ).fetchall()
        close_map: dict[int, float] = {}
        for stock_id, close, _trade_date in price_rows:
            close_map.setdefault(stock_id, float(close))

        contexts: list[AIStockContext] = []
        for row in rows:
            stock = row.stock
            contexts.append(
                AIStockContext(
                    symbol=stock.symbol,
                    company_name=stock.company_name,
                    sector=stock.sector_ref.name if stock.sector_ref else None,
                    industry=stock.industry,
                    exchange=stock.exchange,
                    trade_date=row.trade_date,
                    latest_close=close_map.get(row.stock_id),
                )
            )
        return contexts

    def _build_analytics_items(
        self, rows: list[TechnicalAnalysis]
    ) -> list[AnalyticsListItemRead]:
        items: list[AnalyticsListItemRead] = []
        for row in rows:
            stock = row.stock
            items.append(
                AnalyticsListItemRead(
                    **TechnicalAnalysisRead.model_validate(row).model_dump(),
                    symbol=stock.symbol,
                    company_name=stock.company_name,
                    latest_close=None,
                )
            )
        return items

    # ------------------------------------------------------------------ pipeline

    async def _get_pipeline_status(self) -> AIPipelineContext:
        latest = await self.session.scalar(
            select(EODPipelineRun).order_by(EODPipelineRun.started_at.desc()).limit(1)
        )
        if latest is None:
            return AIPipelineContext()
        return AIPipelineContext(
            has_run=True,
            status=latest.status,
            trade_date=latest.trade_date,
            imported_rows=latest.imported_rows,
            indicators_calculated=latest.indicators_calculated,
            scanner_matches=latest.scanner_matches,
            analytics_calculated=latest.analytics_calculated,
        )

    @staticmethod
    def _latest_trade_date(rows: list[TechnicalAnalysis]) -> date | None:
        return max((row.trade_date for row in rows), default=None)

    # ------------------------------------------------------------------ responses

    def _build_stock_response(
        self,
        stock: Stock,
        analytics: TechnicalAnalysis,
        payload: AIExplanationPayload,
        source: str,
    ) -> AIStockExplanationResponse:
        return AIStockExplanationResponse(
            symbol=stock.symbol,
            company_name=stock.company_name,
            trade_date=analytics.trade_date,
            provider=self.provider.name,
            model=self.provider.model_name(),
            source=source,  # type: ignore[arg-type]
            technical_score=TechnicalAnalysisRead.model_validate(analytics),
            **payload.model_dump(),
        )

    @staticmethod
    def _build_fallback_collection_payload(
        items: list[AnalyticsListItemRead],
    ) -> AICollectionPayload:
        if not items:
            return AICollectionPayload(
                summary="No top-rated stocks available.",
                explanation="No analytics were found to summarise.",
            )
        top = items[0]
        average = round(sum(item.overall_score for item in items) / len(items))
        return AICollectionPayload(
            summary=(
                f"{len(items)} top-rated stocks average {average}/100 overall on "
                f"{top.trade_date}."
            ),
            explanation=(
                f"{top.symbol} leads the group. This explanation is a deterministic "
                "fallback rendered from the supplied analytics."
            ),
            strengths=[f"Top stock: {top.symbol}", f"Group average: {average}/100"],
            risks=["Explanation generated by deterministic fallback (provider unavailable)."],
            opportunities=[item.symbol for item in items],
            confidence=min(100, average),
        )

    @staticmethod
    def _build_fallback_market_payload(
        items: list[AnalyticsListItemRead],
    ) -> AIMarketPayload:
        if not items:
            return AIMarketPayload(
                summary="No market analytics available.",
                explanation="No analytics were found to summarise.",
            )
        top = items[0]
        return AIMarketPayload(
            summary=(
                f"Market remains constructive with {len(items)} top-rated names "
                f"led by {top.symbol}."
            ),
            explanation=(
                "This market summary is a deterministic fallback rendered from the "
                "supplied analytics."
            ),
            strengths=[f"Top name: {top.symbol}"],
            risks=["Fallback mode: provider unavailable."],
            confidence=70,
        )
